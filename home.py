import streamlit as st
from openai import OpenAI


# =========================================================
# НАСТРОЙКИ СТРАНИЦЫ
# =========================================================

st.set_page_config(
    page_title="AI Assistant",
    page_icon="🤖",
    layout="centered",
    initial_sidebar_state="expanded"
)


# =========================================================
# CSS
# =========================================================

st.markdown("""
<style>

.block-container {
    max-width: 900px;
    padding-top: 2rem;
    padding-bottom: 5rem;
}

h1 {
    text-align: center;
}

.subtitle {
    text-align: center;
    color: gray;
    font-size: 18px;
    margin-bottom: 30px;
}

</style>
""", unsafe_allow_html=True)


# =========================================================
# ПРОВЕРКА API-КЛЮЧА
# =========================================================

if "OPENAI_API_KEY" not in st.secrets:
    st.error(
        "API-ключ OpenAI не найден. "
        "Добавьте OPENAI_API_KEY в Streamlit Secrets."
    )
    st.stop()


# =========================================================
# OPENAI CLIENT
# =========================================================

client = OpenAI(
    api_key=st.secrets["OPENAI_API_KEY"]
)


# =========================================================
# SESSION STATE
# =========================================================

if "messages" not in st.session_state:
    st.session_state.messages = []


# =========================================================
# БОКОВАЯ ПАНЕЛЬ
# =========================================================

with st.sidebar:

    st.title("🤖 AI Assistant")

    st.write("Выберите режим работы:")

    mode = st.selectbox(
        "Режим",
        [
            "💬 Обычный помощник",
            "💻 Программист",
            "🎓 Преподаватель"
        ]
    )

    st.divider()

    st.subheader("О проекте")

    st.write("""
    AI-помощник создан с помощью:

    - Python
    - Streamlit
    - OpenAI API
    - GPT-6 Luna
    """)

    st.divider()

    if st.button(
        "🗑 Очистить чат",
        use_container_width=True
    ):
        st.session_state.messages = []
        st.rerun()

    st.divider()

    st.caption("AI Assistant v3.0")


# =========================================================
# ИНСТРУКЦИИ ДЛЯ РЕЖИМОВ
# =========================================================

if mode == "💬 Обычный помощник":

    system_instruction = """
Ты универсальный AI-помощник.

Отвечай пользователю понятно, точно и по существу.

Если вопрос сложный, объясняй его поэтапно.

Используй примеры, когда они помогают понять ответ.

Отвечай на языке, на котором пользователь задаёт вопрос,
если пользователь явно не просит другой язык.
"""


elif mode == "💻 Программист":

    system_instruction = """
Ты опытный программист и AI-помощник по разработке программного обеспечения.

Помогай пользователю:

- писать программы;
- исправлять ошибки;
- понимать программный код;
- изучать программирование;
- улучшать существующий код;
- проектировать приложения.

Особенно хорошо работай с:

- Python
- Java
- C++
- HTML
- CSS
- JavaScript
- SQL

Если пользователь присылает код с ошибкой:

1. Найди ошибку.
2. Объясни причину простыми словами.
3. Покажи проблемное место.
4. Дай исправленный вариант кода.
5. Объясни, что именно изменилось.

Код обязательно оформляй в Markdown-блоках кода.

Для начинающих объясняй без лишнего усложнения.
"""


elif mode == "🎓 Преподаватель":

    system_instruction = """
Ты AI-помощник преподавателя.

Твоя задача — помогать объяснять учебный материал
понятным языком.

Ты можешь создавать:

- объяснения тем;
- лекции;
- практические задания;
- самостоятельные работы;
- вопросы;
- тесты;
- примеры;
- упражнения;
- планы занятий.

Если тема связана с программированием,
приводи понятные примеры кода.

Если пользователь просит задания для студентов,
не давай сразу ответы, если он отдельно не попросил решения.

Структурируй материал так, чтобы его было удобно
использовать на занятии.
"""


# =========================================================
# ЗАГОЛОВОК
# =========================================================

st.title("🤖 AI Assistant")

if mode == "💬 Обычный помощник":
    description = "Универсальный AI-помощник"

elif mode == "💻 Программист":
    description = "Помощник по программированию и поиску ошибок"

else:
    description = "Помощник для подготовки учебных материалов"


st.markdown(
    f'<div class="subtitle">{description}</div>',
    unsafe_allow_html=True
)


# =========================================================
# ПРИВЕТСТВИЕ
# =========================================================

if len(st.session_state.messages) == 0:

    with st.chat_message("assistant"):

        if mode == "💬 Обычный помощник":

            st.markdown("""
Привет! 👋

Я универсальный AI-помощник.

Задай мне любой вопрос.
""")

        elif mode == "💻 Программист":

            st.markdown("""
Привет! 👋

Я помогу с программированием.

Можешь:

- отправить код;
- прислать ошибку;
- попросить написать программу;
- попросить объяснить код;
- задать вопрос по Java, Python, C++ и другим языкам.
""")

        elif mode == "🎓 Преподаватель":

            st.markdown("""
Привет! 👋

Я AI-помощник преподавателя.

Могу помочь создать:

- задания;
- практические работы;
- тесты;
- объяснения;
- лекционный материал;
- примеры для студентов.
""")


# =========================================================
# ПОКАЗЫВАЕМ ИСТОРИЮ
# =========================================================

for message in st.session_state.messages:

    with st.chat_message(message["role"]):
        st.markdown(message["content"])


# =========================================================
# ПОЛЕ ВВОДА
# =========================================================

prompt = st.chat_input(
    "Введите сообщение..."
)


# =========================================================
# ОБРАБОТКА СООБЩЕНИЯ
# =========================================================

if prompt:

    # Добавляем сообщение пользователя в историю
    st.session_state.messages.append(
        {
            "role": "user",
            "content": prompt
        }
    )

    # Показываем сообщение пользователя
    with st.chat_message("user"):
        st.markdown(prompt)


    # =====================================================
    # ЗАПРОС К OPENAI
    # =====================================================

    with st.chat_message("assistant"):

        with st.spinner("Думаю..."):

            try:

                response = client.responses.create(

                    model="gpt-6-luna",

                    reasoning={
                        "effort": "low"
                    },

                    instructions=system_instruction,

                    input=st.session_state.messages,

                    max_output_tokens=2000
                )


                answer = response.output_text


                # Если по какой-то причине пришёл пустой ответ
                if not answer:
                    answer = "Не удалось получить текстовый ответ."


                # Показываем ответ
                st.markdown(answer)


                # Сохраняем ответ в историю
                st.session_state.messages.append(
                    {
                        "role": "assistant",
                        "content": answer
                    }
                )


            except Exception as error:

                st.error(
                    "Произошла ошибка при обращении к OpenAI API."
                )

                st.code(str(error))
